"""Writes Kigo's Haiku vector icon (HVIF) and the resource file around it.

usage: python3 -I haiku/mkicon.py   (rewrites haiku/Kigo.rdef)

The icon: a deep-blue rounded tile with a white magnifier and an orange
handle, plus a small yellow spark. Shapes are polygons on the
64x64 HVIF grid; circles and rounded corners are sampled arcs.
"""
import math
import os


def rounded_rect(x0, y0, x1, y1, r, steps=6):
    points = []
    corners = [(x1 - r, y0 + r, -90), (x1 - r, y1 - r, 0), (x0 + r, y1 - r, 90), (x0 + r, y0 + r, 180)]
    for cx, cy, start in corners:
        for i in range(steps + 1):
            a = math.radians(start + 90 * i / steps)
            points.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return points


def circle(cx, cy, r, steps=28):
    return [(cx + r * math.cos(2 * math.pi * i / steps), cy + r * math.sin(2 * math.pi * i / steps))
            for i in range(steps)]


def bar(x0, y0, x1, y1, width):
    """A thick line from (x0, y0) to (x1, y1) with rounded-ish ends."""
    dx, dy = x1 - x0, y1 - y0
    length = math.hypot(dx, dy)
    nx, ny = -dy / length * width / 2, dx / length * width / 2
    return [(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)]


def star(cx, cy, outer, inner):
    points = []
    for i in range(8):
        r = outer if i % 2 == 0 else inner
        a = math.radians(-90 + 45 * i)
        points.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return points


colors = {
    "shadow": (0, 0, 0, 0x50),
    "rim": (0x1c, 0x2a, 0x5a, 0xff),
    "tile": (0x2f, 0x4f, 0xb8, 0xff),
    "glow": (0x45, 0x6c, 0xdc, 0xff),
    "ring": (0xf4, 0xf6, 0xff, 0xff),
    "lens": (0x26, 0x40, 0x9c, 0xff),
    "shine": (0x5f, 0x84, 0xec, 0xff),
    "handle": (0xff, 0x82, 0x03, 0xff),
    "spark": (0xff, 0xd0, 0x5a, 0xff),
}
shapes = [
    ("shadow", rounded_rect(5, 7, 61, 62, 12)),
    ("rim", rounded_rect(3, 3, 60, 60, 12)),
    ("tile", rounded_rect(4.5, 4.5, 58.5, 58.5, 11)),
    ("glow", rounded_rect(4.5, 4.5, 58.5, 30, 11)),
    ("handle", bar(37, 37, 50, 50, 7.5)),
    ("ring", circle(27, 27, 15.5)),
    ("lens", circle(27, 27, 11.5)),
    ("shine", [(19.5, 25), (21.5, 20.5), (25.5, 17.8), (27, 20.5), (23.5, 22.5), (22, 26)]),
    ("spark", star(48, 15, 7, 2.2)),
]


def coord(v):
    n = round((v + 128.0) * 102.0)
    return bytes([0x80 | (n >> 8), n & 0xff])


names = list(colors)
out = bytearray(b"ncif")
out.append(len(names))
for name in names:
    out += bytes([0x01, *colors[name]])          # solid color style
out.append(len(shapes))
for _, points in shapes:
    out += bytes([0x0a, len(points)])           # closed path, no curves
    for x, y in points:
        out += coord(x) + coord(y)
out.append(len(shapes))
for i, (style, _) in enumerate(shapes):
    out += bytes([0x0a, names.index(style), 1, i, 0x00])

here = os.path.dirname(os.path.abspath(__file__))
major, middle, minor = (open(os.path.join(here, "..", "VERSION")).read().strip().split(".") + ["0", "0"])[:3]
hexdata = out.hex()
lines = "\n".join(f'\t$"{hexdata[i:i + 64]}"' for i in range(0, len(hexdata), 64))
rdef = f'''// Generated by haiku/mkicon.py; edit that, not this.

resource app_signature "application/x-vnd.bluevisor-Kigo";

resource app_flags B_SINGLE_LAUNCH | B_BACKGROUND_APP;

resource app_version {{
	major  = {major},
	middle = {middle},
	minor  = {minor},
	variety = B_APPV_DEVELOPMENT,
	internal = 0,
	short_info = "Kigo",
	long_info = "A Spotlight and Raycast style launcher for Haiku"
}};

resource vector_icon array {{
{lines}
}};
'''
open(os.path.join(here, "Kigo.rdef"), "w").write(rdef)
open(os.path.join(here, "kigo.hvif"), "wb").write(out)
print(len(out), "bytes")
